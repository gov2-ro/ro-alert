const MONTH_NAMES = {
  ro: ["Ianuarie", "Februarie", "Martie", "Aprilie", "Mai", "Iunie", "Iulie", "August", "Septembrie", "Octombrie", "Noiembrie", "Decembrie"],
  en: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
};

/* Month name for a number 1..12 in the given language (default: the UI language). */
function monthName(n, lang) {
  const l = lang || (window.state && state.lang) || "ro";
  return (MONTH_NAMES[l] || MONTH_NAMES.ro)[n - 1] || "";
}

function t(key) {
  const lang = (window.state && state.lang) || "ro";
  return (I18N[lang] && I18N[lang][key]) || (I18N.ro[key]) || key;
}

/* Apply translations to any element carrying data-i18n / data-i18n-ph. */
function applyI18n() {
  document.documentElement.lang = (window.state && state.lang) || "ro";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));   // trusted dictionary text only
  });
  document.querySelectorAll("[data-i18n-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-label")));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
}
